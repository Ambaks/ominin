/*
 * Ce qu'Ominin offre vraiment à ses clients, fonctionnalité par fonctionnalité :
 * l'agent social en présente une par publication, en tournant sur tout le
 * catalogue (backend, social_draft). Le rédacteur lit ce catalogue par
 * /api/social/features ; « does » est tout ce qu'il peut affirmer, il ne dit
 * rien de plus.
 *
 * Pour l'instant, le compte Menu seulement.
 */

